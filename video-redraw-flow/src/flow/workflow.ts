export type CopySnapshot = {
  nodes: (WorkflowNode | PhaseNode)[]
  edges: WorkflowEdge[]
}

/** 深拷贝原始流程作为编辑副本；原始常量本身永远不被修改。 */
export function createCopySnapshot(): CopySnapshot {
  const nodes = structuredClone(initialNodes).map((node) =>
    node.type === 'workflow'
      ? { ...node, draggable: true, connectable: true }
      : { ...node, draggable: false, selectable: false },
  )
  const edges = structuredClone(flowEdges)
  return { nodes, edges }
}

